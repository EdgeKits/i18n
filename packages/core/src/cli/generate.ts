import { fallbackIdentifier, formatTranslationKvKey } from '../key-format.ts'

/**
 * The CLI's code generation, as pure functions of the collected locale tree: no
 * filesystem, so the emitted text is testable. Formats are those of the site's
 * `scripts/bundle-translations.ts`, header aside.
 */

export type TranslationTree = Record<string, unknown>

// <locale> → <namespace> → the namespace's JSON
export type CollectedData = Record<string, Record<string, TranslationTree>>

export type KvBulkEntry = { key: string; value: string }

const HEADER = `// Auto-generated by @edgekits/astro-i18n (edgekits-i18n CLI)
// Do not edit manually.
`

// A namespace becomes part of a KV key, a cache URL and (dots as `__`) the
// `FALLBACK_<NAMESPACE>` identifier, so its file name is restricted to what is valid in
// all three: segments of [a-z0-9_], joined by single dots (`app.billing`).
export const NAMESPACE_NAME = /^[a-z0-9][a-z0-9_]*(\.[a-z0-9][a-z0-9_]*)*$/

// `fallbacks.generated.ts` exports FALLBACK_LOCALE (the default locale's code) beside one
// FALLBACK_<NAMESPACE> per namespace: a namespace `locale` would export it twice.
const RESERVED_NAMESPACES = new Set(['locale'])

/**
 * Throws, naming the offender, when a locale folder is not one of the config's
 * `languages`, a namespace file name does not match NAMESPACE_NAME or is reserved
 * (`locale`), or two namespaces compile to the same fallback identifier (`app.billing` and
 * `app__billing`). Run on the collected tree before anything is generated or pushed.
 */
export function assertValidNames(collected: CollectedData, languages: Readonly<Record<string, unknown>>): void {
  const configured = Object.keys(languages)

  for (const [locale, namespaces] of Object.entries(collected)) {
    if (!configured.includes(locale)) {
      throw new Error(
        `Locale folder "${locale}" is not one of \`languages\` in edgekits-i18n.config.ts: ${configured.join(', ')}.`,
      )
    }
    const identifiers = new Map<string, string>()
    for (const ns of Object.keys(namespaces)) {
      if (!NAMESPACE_NAME.test(ns)) {
        throw new Error(
          `Namespace "${ns}" (${locale}/${ns}.json) must match ${NAMESPACE_NAME}: ` +
            'segments of lowercase letters, digits and underscores, joined by single dots.',
        )
      }
      if (RESERVED_NAMESPACES.has(ns)) {
        throw new Error(
          `Namespace "${ns}" (${locale}/${ns}.json) is reserved: its fallback would be exported as ` +
            `${fallbackIdentifier(ns)}, which fallbacks.generated.ts already exports (the default locale's code). ` +
            'Rename the file.',
        )
      }
      const identifier = fallbackIdentifier(ns)
      const other = identifiers.get(identifier)
      if (other !== undefined) {
        throw new Error(
          `Namespaces "${other}" (${locale}/${other}.json) and "${ns}" (${locale}/${ns}.json) ` +
            `both compile to ${identifier}. Rename one of them.`,
        )
      }
      identifiers.set(identifier, ns)
    }
  }
}

function nullValueError(keyPath: string, file: string): Error {
  return new Error(
    `Key "${keyPath}" (${file}) is null: it would override the default locale's text with null. ` +
      'Remove the key to fall back, or give it a value.',
  )
}

// The first null in `value`, as a key path below `keyPath` (`a.b`, `list[2]`), or null.
function findNull(value: unknown, keyPath: string): string | null {
  if (value === null) return keyPath
  if (Array.isArray(value)) {
    for (let i = 0; i < value.length; i++) {
      const found = findNull(value[i], `${keyPath}[${i}]`)
      if (found !== null) return found
    }
  } else if (isTree(value)) {
    for (const [key, child] of Object.entries(value)) {
      const found = findNull(child, `${keyPath}.${key}`)
      if (found !== null) return found
    }
  }
  return null
}

/**
 * Throws, naming the key path and the file, on the first `null` in any locale: merged over
 * the compiled fallback, a null replaces the default locale's text.
 */
export function assertNoNullValues(collected: CollectedData): void {
  for (const [locale, namespaces] of Object.entries(collected)) {
    for (const [ns, json] of Object.entries(namespaces)) {
      const found = findNull(json, ns)
      if (found !== null) throw nullValueError(found, `${locale}/${ns}.json`)
    }
  }
}

/**
 * A single-quoted TS string literal, escaped by JSON.stringify. For every name the
 * validation accepts it is byte-identical to the plain `'name'` the CLI always wrote, so
 * existing generated files do not change; anything else comes out escaped, not injected.
 */
export function quoteString(value: string): string {
  const escaped = JSON.stringify(value).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")
  return `'${escaped}'`
}

/** Locales that have at least one namespace, sorted. */
export function localesWithTranslations(collected: CollectedData): string[] {
  return Object.keys(collected).sort()
}

/**
 * The locale the schema and the namespace list are derived from: the default locale
 * when it has translations, otherwise the first locale that does.
 */
export function schemaSourceLocale(collected: CollectedData, defaultLocale: string): string | undefined {
  if (collected[defaultLocale]) return defaultLocale
  return localesWithTranslations(collected)[0]
}

/** `wrangler kv bulk put` input: one entry per locale and namespace. */
export function buildBulkData(collected: CollectedData, keyPrefix: string): KvBulkEntry[] {
  const bulkData: KvBulkEntry[] = []

  for (const [locale, namespaces] of Object.entries(collected)) {
    for (const [ns, json] of Object.entries(namespaces)) {
      bulkData.push({ key: formatTranslationKvKey(keyPrefix, locale, ns), value: JSON.stringify(json) })
    }
  }

  return bulkData
}

function isTree(value: unknown): value is TranslationTree {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

// The JSON kind of an array element; an array is typed only when all its elements share one.
function jsonKind(value: unknown): string {
  if (value === null) return 'null'
  if (Array.isArray(value)) return 'array'
  return typeof value
}

// A scalar leaf's TS type: numbers and booleans as such, everything else `string`.
function scalarType(value: unknown): string {
  if (typeof value === 'number') return 'number'
  if (typeof value === 'boolean') return 'boolean'
  return 'string'
}

/**
 * Throws, naming the key path (with element indexes) and the file, on what the schema
 * cannot type: a null, or an array that mixes kinds of elements (strings and objects).
 */
function assertTypeable(value: unknown, keyPath: string, file: string): void {
  if (value === null) throw nullValueError(keyPath, file)

  if (Array.isArray(value)) {
    const nullAt = value.indexOf(null)
    if (nullAt !== -1) throw nullValueError(`${keyPath}[${nullAt}]`, file)

    const kinds = [...new Set(value.map(jsonKind))]
    if (kinds.length > 1) {
      throw new Error(
        `Key "${keyPath}" (${file}) is an array that mixes ${kinds.join(', ')} elements: ` +
          'I18n.Schema cannot type it. Use one kind of element per array.',
      )
    }
    value.forEach((element, i) => assertTypeable(element, `${keyPath}[${i}]`, file))
  } else if (isTree(value)) {
    for (const [key, child] of Object.entries(value)) assertTypeable(child, `${keyPath}.${key}`, file)
  }
}

/**
 * The TS type of the values found at one place in the tree (one value, or the same key
 * across the elements of an array), checked by assertTypeable first. Objects merge into one
 * object type, arrays into one array type, and the distinct kinds that remain form a union
 * (`string | number` for a key that is a string in one element and a number in another).
 */
function typeOfValues(values: readonly unknown[], indent: number): string {
  const objects = values.filter(isTree)
  const arrays = values.filter(Array.isArray)
  const scalars = [...new Set(values.filter((value) => !isTree(value) && !Array.isArray(value)).map(scalarType))]

  return [
    ...(objects.length > 0 ? [objectType(objects, indent)] : []),
    ...(arrays.length > 0 ? [arrayType(arrays, indent)] : []),
    ...scalars,
  ].join(' | ')
}

/**
 * One object type for a list of objects (one object, or every element of an array): each
 * key in first-seen order, required when every object has it, optional (`?:`) otherwise,
 * typed by typeOfValues over the objects that have it.
 */
function objectType(objects: readonly TranslationTree[], indent: number): string {
  const keys = [...new Set(objects.flatMap((object) => Object.keys(object)))]
  if (keys.length === 0) return '{}'

  const pad = ' '.repeat(indent)
  const padInner = ' '.repeat(indent + 2)
  const lines = keys.map((key) => {
    const present = objects.filter((object) => Object.hasOwn(object, key))
    const optional = present.length < objects.length ? '?' : ''
    return `${padInner}${JSON.stringify(key)}${optional}: ${typeOfValues(
      present.map((object) => object[key]),
      indent + 2,
    )}`
  })

  return `{\n${lines.join(';\n')};\n${pad}}`
}

/**
 * One array type for a list of arrays (one array, or the same key's arrays across the
 * elements of an outer one): the elements of all of them typed together. `string[]` when
 * they are all empty, `<scalar>[]` for one scalar kind, `Array<…>` otherwise.
 */
function arrayType(arrays: readonly unknown[][], indent: number): string {
  const elements = arrays.flat(1)
  if (elements.length === 0) return 'string[]'

  const elementType = typeOfValues(elements, indent)
  return elements.every((element) => !isTree(element) && !Array.isArray(element)) && !elementType.includes('|')
    ? `${elementType}[]`
    : `Array<${elementType}>`
}

/** The TS type of one namespace's JSON (see typeOfValues). */
function generateSchemaTs(value: unknown, indent: number, keyPath: string, file: string): string {
  assertTypeable(value, keyPath, file)
  return typeOfValues([value], indent)
}

/**
 * `src/i18n.generated.d.ts`: the global `I18n.Schema`, from the schema source locale.
 * Throws, naming the key, when an array in it mixes kinds of elements or a value is null.
 */
export function buildTypesContent(collected: CollectedData, defaultLocale: string): string {
  const source = schemaSourceLocale(collected, defaultLocale)
  const schemaObject: TranslationTree = (source && collected[source]) || {}

  const namespaceLines = Object.entries(schemaObject).map(([ns, value]) => {
    const valueTs = generateSchemaTs(value, 10, ns, `${source}/${ns}.json`)
    return `      ${JSON.stringify(ns)}: ${valueTs}`
  })

  const interfaceBody =
    namespaceLines.length > 0
      ? `    export interface Schema {\n${namespaceLines.join(';\n')};\n    }`
      : `    export interface Schema {}`

  return `${HEADER}
declare global {
  namespace I18n {
${interfaceBody}
  }
}

export {}
`
}

/**
 * `runtime-constants.ts`:
 *   - NAMESPACE_KEYS            -> from the schema source locale (default locale preferred)
 *   - LOCALES_WITH_TRANSLATIONS -> from all collected locales
 *   - FULLY_TRANSLATED_LOCALES  -> locales that have ALL namespace keys
 */
export function buildRuntimeConstantsContent(collected: CollectedData, defaultLocale: string): string {
  const source = schemaSourceLocale(collected, defaultLocale)
  const namespaceKeys = Object.keys((source && collected[source]) || {}).sort()
  const locales = localesWithTranslations(collected)

  const fullyTranslatedLocales = locales.filter((locale) => {
    const localeNamespaces = Object.keys(collected[locale] || {})
    return namespaceKeys.every((ns) => localeNamespaces.includes(ns))
  })

  return `${HEADER}
export const NAMESPACE_KEYS = [${namespaceKeys.map(quoteString).join(', ')}] as [string, ...string[]];

export const LOCALES_WITH_TRANSLATIONS = [${locales.map(quoteString).join(', ')}] as const;

export const FULLY_TRANSLATED_LOCALES = [${fullyTranslatedLocales.map(quoteString).join(', ')}] as const;
`
}

/**
 * `fallbacks.generated.ts`: one `FALLBACK_<NAMESPACE>` (`fallbackIdentifier`) per
 * default-locale namespace.
 * Null when the default locale has no translations (nothing to fall back to).
 */
export function buildFallbacksContent(collected: CollectedData, defaultLocale: string): string | null {
  const fallbackNamespaces = collected[defaultLocale]
  if (!fallbackNamespaces) return null

  const lines: string[] = [HEADER]
  lines.push(`export const FALLBACK_LOCALE = ${JSON.stringify(defaultLocale)} as const;\n`)

  for (const [ns, json] of Object.entries(fallbackNamespaces)) {
    lines.push(`export const ${fallbackIdentifier(ns)} = ${JSON.stringify(json, null, 2)} as const;\n`)
  }

  return lines.join('\n')
}

// Leaf key paths in `tree` that `base` lacks: a key missing from `base` counts once, with
// whatever it holds; arrays are leaves.
function extraKeyPaths(tree: TranslationTree, base: TranslationTree, prefix = ''): string[] {
  const paths: string[] = []
  for (const [key, child] of Object.entries(tree)) {
    const keyPath = prefix ? `${prefix}.${key}` : key
    if (!Object.hasOwn(base, key)) {
      paths.push(keyPath)
    } else {
      const baseChild = base[key]
      if (isTree(child) && isTree(baseChild)) paths.push(...extraKeyPaths(child, baseChild, keyPath))
    }
  }
  return paths
}

/**
 * Warnings about what I18n.Schema and the fallbacks will not cover, compared with the
 * default locale: a namespace no default-locale file has, and keys a locale's file has
 * that the default locale's lacks (a count per file, the first three paths). Empty when
 * the default locale has no translations (the CLI warns about that on its own).
 */
export function translationWarnings(collected: CollectedData, defaultLocale: string): string[] {
  const base = collected[defaultLocale]
  if (!base) return []

  const orphans = new Map<string, string[]>()
  const extraKeys: string[] = []

  for (const [locale, namespaces] of Object.entries(collected)) {
    if (locale === defaultLocale) continue
    for (const [ns, tree] of Object.entries(namespaces)) {
      const baseTree = base[ns]
      if (baseTree === undefined) {
        orphans.set(ns, [...(orphans.get(ns) ?? []), locale])
        continue
      }
      const extra = isTree(tree) && isTree(baseTree) ? extraKeyPaths(tree, baseTree) : []
      if (extra.length > 0) {
        const shownPaths = extra.slice(0, 3).join(', ') + (extra.length > 3 ? ', …' : '')
        extraKeys.push(
          `${locale}/${ns}.json has ${extra.length} ${extra.length === 1 ? 'key' : 'keys'} that ` +
            `${defaultLocale}/${ns}.json lacks (not in I18n.Schema): ${shownPaths}`,
        )
      }
    }
  }

  return [
    ...[...orphans].map(
      ([ns, locales]) =>
        `Namespace "${ns}" exists only in ${locales.join(', ')} (no ${defaultLocale}/${ns}.json): ` +
        'it is not in I18n.Schema and has no fallback.',
    ),
    ...extraKeys,
  ]
}
