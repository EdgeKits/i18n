import assert from 'node:assert/strict'
import test from 'node:test'

import {
  assertValidNames,
  buildBulkData,
  buildFallbacksContent,
  buildRuntimeConstantsContent,
  buildTypesContent,
  quoteString,
  schemaSourceLocale,
} from '../src/cli/generate.ts'
import { assembleNamespace } from '../src/assemble.ts'
import { ARRAY_TREE, LOCALE_TREE } from './fixtures/locales.ts'

const HEADER = '// Auto-generated by @edgekits/astro-i18n (edgekits-i18n CLI)\n// Do not edit manually.\n'

test('schema: I18n.Schema mirrors the default locale tree, leaves typed as string', () => {
  assert.equal(
    buildTypesContent(LOCALE_TREE, 'en'),
    `${HEADER}
declare global {
  namespace I18n {
    export interface Schema {
      "common": {
            "title": string;
            "nav": {
              "home": string;
            };
          };
      "blog": {
            "heading": string;
          };
    }
  }
}

export {}
`,
  )
})

test('schema: lists are typed: string[] for strings and empty lists, Array<…> from the first element', () => {
  assert.equal(
    buildTypesContent(ARRAY_TREE, 'en'),
    `${HEADER}
declare global {
  namespace I18n {
    export interface Schema {
      "faq": {
            "title": string;
            "tags": string[];
            "items": Array<{
              "q": string;
              "a": string;
              "links": string[];
            }>;
            "empty": string[];
            "grid": Array<string[]>;
          };
    }
  }
}

export {}
`,
  )
})

test('schema: other scalars stay string, in a list too', () => {
  const content = buildTypesContent({ en: { stats: { count: 3, on: true, years: [2025, 2026] } } }, 'en')
  assert.match(content, /"count": string;\n {12}"on": string;\n {12}"years": string\[\];/)
})

test('schema: a list that mixes kinds of elements stops generation, naming the key and the file', () => {
  assert.throws(() => buildTypesContent({ en: { faq: { list: ['a', { q: 'b' }] } } }, 'en'), {
    message:
      'Key "faq.list" (en/faq.json) is an array that mixes string, object elements: ' +
      'I18n.Schema cannot type it. Use one kind of element per array.',
  })
  assert.throws(
    () => buildTypesContent({ en: { faq: { items: [{ links: ['/a/', 2] }] } } }, 'en'),
    /^Error: Key "faq\.items\[0\]\.links" \(en\/faq\.json\) is an array that mixes string, number elements/,
  )
})

test('schema: an empty tree yields an empty Schema', () => {
  assert.match(buildTypesContent({}, 'en'), /export interface Schema \{\}/)
})

test('schema source: the default locale, else the first locale with translations', () => {
  assert.equal(schemaSourceLocale(LOCALE_TREE, 'en'), 'en')
  assert.equal(schemaSourceLocale(LOCALE_TREE, 'fr'), 'de')
  assert.equal(schemaSourceLocale({}, 'en'), undefined)
})

test('runtime constants: namespaces from the source locale, full translation per locale', () => {
  assert.equal(
    buildRuntimeConstantsContent(LOCALE_TREE, 'en'),
    `${HEADER}
export const NAMESPACE_KEYS = ['blog', 'common'] as [string, ...string[]];

export const LOCALES_WITH_TRANSLATIONS = ['de', 'en'] as const;

export const FULLY_TRANSLATED_LOCALES = ['en'] as const;
`,
  )
})

test('fallbacks: one FALLBACK_<NAMESPACE> per default-locale namespace', () => {
  const content = buildFallbacksContent(LOCALE_TREE, 'en')
  assert.ok(content)
  assert.ok(content.startsWith(`${HEADER}\nexport const FALLBACK_LOCALE = "en" as const;\n`))
  assert.match(content, /export const FALLBACK_COMMON = \{\n {2}"title": "Hello",/)
  assert.match(content, /export const FALLBACK_BLOG = \{\n {2}"heading": "Blog"\n\} as const;/)
  assert.equal(buildFallbacksContent(LOCALE_TREE, 'fr'), null, 'no default-locale tree, no fallbacks')
})

test('lists end to end: JSON -> compiled fallbacks -> assembled namespace, each list whole', async () => {
  const content = buildFallbacksContent(ARRAY_TREE, 'en')
  assert.ok(content)

  // The generated module, run as JavaScript (`as const` is its only TypeScript).
  const source = content.replace(/ as const;/g, ';')
  const fallbacks = (await import(`data:text/javascript,${encodeURIComponent(source)}`)) as Record<string, unknown>
  assert.deepEqual(fallbacks.FALLBACK_FAQ, ARRAY_TREE.en.faq, 'the fallbacks carry the lists unchanged')

  // `de` from KV over the `en` fallback: overridden lists replace the fallback's, the rest
  // comes from `en`.
  const assembled = assembleNamespace(ARRAY_TREE.de.faq, fallbacks.FALLBACK_FAQ)
  assert.deepEqual(assembled, {
    title: 'FAQ',
    tags: ['Edge'],
    items: [{ q: 'Warum KV?', a: 'Lesen am Edge.', links: ['/de/docs/'] }],
    empty: [],
    grid: [
      ['a', 'b'],
      ['c', 'd'],
    ],
  })

  // KV receives the lists as JSON.
  const [entry] = buildBulkData({ de: ARRAY_TREE.de }, 'p')
  assert.deepEqual(JSON.parse(entry!.value), ARRAY_TREE.de.faq)
})

test('bulk data: <prefix>:<namespace>:<locale> keys, JSON-string values', () => {
  assert.deepEqual(buildBulkData(LOCALE_TREE, 'edgekits.dev'), [
    { key: 'edgekits.dev:common:en', value: '{"title":"Hello","nav":{"home":"Home"}}' },
    { key: 'edgekits.dev:blog:en', value: '{"heading":"Blog"}' },
    { key: 'edgekits.dev:common:de', value: '{"title":"Hallo","nav":{"home":"Startseite"}}' },
  ])
})

// Audit 2026-10-12 A05-1: names reach generated TypeScript, so they are validated first,
// and every string literal is escaped.

const LANGUAGES = { en: {}, de: {} }

test('names: configured locale folders and lowercase namespace names pass', () => {
  assert.doesNotThrow(() => assertValidNames(LOCALE_TREE, LANGUAGES))
  assert.doesNotThrow(() => assertValidNames({ en: { common: {}, page_2: {}, '404': {} } }, LANGUAGES))
})

test('names: a namespace file name outside [a-z0-9_] is rejected, naming it', () => {
  for (const ns of ['my-ns', 'Common', '_draft', "it's", 'a.b']) {
    assert.throws(
      () => assertValidNames({ en: { [ns]: {} } }, LANGUAGES),
      (err: Error) => err.message.startsWith(`Namespace "${ns}" (en/${ns}.json) must match`),
      ns,
    )
  }
})

test('names: a locale folder that is not one of `languages` is rejected, naming it', () => {
  assert.throws(
    () => assertValidNames({ en: { common: {} }, fr: { common: {} } }, LANGUAGES),
    /Locale folder "fr" is not one of `languages` in edgekits-i18n\.config\.ts: en, de\./,
  )
})

test('quoteString: plain names keep the single-quoted form; anything else is escaped, not injected', () => {
  assert.equal(quoteString('common'), "'common'")
  assert.equal(quoteString('pt-br'), "'pt-br'")

  for (const value of ["it's", 'say "hi"', 'back\\slash', "'];process.exit(1);['", 'line\nbreak', ' ']) {
    const literal = quoteString(value)
    assert.ok(literal.startsWith("'") && literal.endsWith("'"), literal)
    // The literal evaluates to exactly the input: nothing escapes the string.
    assert.equal(new Function(`return ${literal}`)(), value, literal)
  }
})
