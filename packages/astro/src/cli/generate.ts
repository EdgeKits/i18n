import { formatTranslationKvKey } from '../key-format.ts'

/**
 * The CLI's code generation, as pure functions of the collected locale tree: no
 * filesystem, so the emitted text is testable. Formats are those of the site's
 * `scripts/bundle-translations.ts`, header aside.
 */

export type TranslationTree = Record<string, unknown>

// <locale> → <namespace> → the namespace's JSON
export type CollectedData = Record<string, Record<string, TranslationTree>>

export type KvBulkEntry = { key: string; value: string }

const HEADER = `// Auto-generated by @edgekits/astro-i18n (edgekits-i18n CLI)
// Do not edit manually.
`

// A namespace becomes part of a KV key, a cache URL and the `FALLBACK_<NAMESPACE>`
// identifier, so its file name is restricted to what is valid in all three.
export const NAMESPACE_NAME = /^[a-z0-9][a-z0-9_]*$/

/**
 * Throws, naming the offender, when a locale folder is not one of the config's
 * `languages` or a namespace file name does not match NAMESPACE_NAME. Run on the
 * collected tree before anything is generated or pushed.
 */
export function assertValidNames(collected: CollectedData, languages: Readonly<Record<string, unknown>>): void {
  const configured = Object.keys(languages)

  for (const [locale, namespaces] of Object.entries(collected)) {
    if (!configured.includes(locale)) {
      throw new Error(
        `Locale folder "${locale}" is not one of \`languages\` in edgekits-i18n.config.ts: ${configured.join(', ')}.`,
      )
    }
    for (const ns of Object.keys(namespaces)) {
      if (!NAMESPACE_NAME.test(ns)) {
        throw new Error(
          `Namespace "${ns}" (${locale}/${ns}.json) must match ${NAMESPACE_NAME}: lowercase letters, digits and underscores.`,
        )
      }
    }
  }
}

/**
 * A single-quoted TS string literal, escaped by JSON.stringify. For every name the
 * validation accepts it is byte-identical to the plain `'name'` the CLI always wrote, so
 * existing generated files do not change; anything else comes out escaped, not injected.
 */
export function quoteString(value: string): string {
  const escaped = JSON.stringify(value).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'")
  return `'${escaped}'`
}

/** Locales that have at least one namespace, sorted. */
export function localesWithTranslations(collected: CollectedData): string[] {
  return Object.keys(collected).sort()
}

/**
 * The locale the schema and the namespace list are derived from: the default locale
 * when it has translations, otherwise the first locale that does.
 */
export function schemaSourceLocale(collected: CollectedData, defaultLocale: string): string | undefined {
  if (collected[defaultLocale]) return defaultLocale
  return localesWithTranslations(collected)[0]
}

/** `wrangler kv bulk put` input: one entry per locale and namespace. */
export function buildBulkData(collected: CollectedData, keyPrefix: string): KvBulkEntry[] {
  const bulkData: KvBulkEntry[] = []

  for (const [locale, namespaces] of Object.entries(collected)) {
    for (const [ns, json] of Object.entries(namespaces)) {
      bulkData.push({ key: formatTranslationKvKey(keyPrefix, locale, ns), value: JSON.stringify(json) })
    }
  }

  return bulkData
}

function isTree(value: unknown): value is TranslationTree {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

// The JSON kind of an array element; an array is typed only when all its elements share one.
function jsonKind(value: unknown): string {
  if (value === null) return 'null'
  if (Array.isArray(value)) return 'array'
  return typeof value
}

/**
 * The TS type of one JSON value. Objects become object types; arrays become `string[]`
 * (strings, other scalars, or empty) or `Array<…>` typed from their first element
 * (objects, nested arrays); every other leaf stays `string`. `keyPath` and `file` name the
 * value in the error a mixed array raises.
 */
function generateSchemaTs(value: unknown, indent: number, keyPath: string, file: string): string {
  if (Array.isArray(value)) {
    if (value.length === 0) return 'string[]'

    const kinds = [...new Set(value.map(jsonKind))]
    if (kinds.length > 1) {
      throw new Error(
        `Key "${keyPath}" (${file}) is an array that mixes ${kinds.join(', ')} elements: ` +
          'I18n.Schema cannot type it. Use one kind of element per array.',
      )
    }

    const first = value[0]
    if (!isTree(first) && !Array.isArray(first)) return 'string[]'
    return `Array<${generateSchemaTs(first, indent, `${keyPath}[0]`, file)}>`
  }

  if (!isTree(value)) return 'string'

  const entries = Object.entries(value)
  if (entries.length === 0) return '{}'

  const pad = ' '.repeat(indent)
  const padInner = ' '.repeat(indent + 2)
  const lines = entries.map(
    ([key, child]) =>
      `${padInner}${JSON.stringify(key)}: ${generateSchemaTs(child, indent + 2, `${keyPath}.${key}`, file)}`,
  )

  return `{\n${lines.join(';\n')};\n${pad}}`
}

/**
 * `src/i18n.generated.d.ts`: the global `I18n.Schema`, from the schema source locale.
 * Throws, naming the key, when an array in it mixes kinds of elements.
 */
export function buildTypesContent(collected: CollectedData, defaultLocale: string): string {
  const source = schemaSourceLocale(collected, defaultLocale)
  const schemaObject: TranslationTree = (source && collected[source]) || {}

  const namespaceLines = Object.entries(schemaObject).map(([ns, value]) => {
    const valueTs = generateSchemaTs(value, 10, ns, `${source}/${ns}.json`)
    return `      ${JSON.stringify(ns)}: ${valueTs}`
  })

  const interfaceBody =
    namespaceLines.length > 0
      ? `    export interface Schema {\n${namespaceLines.join(';\n')};\n    }`
      : `    export interface Schema {}`

  return `${HEADER}
declare global {
  namespace I18n {
${interfaceBody}
  }
}

export {}
`
}

/**
 * `runtime-constants.ts`:
 *   - NAMESPACE_KEYS            -> from the schema source locale (default locale preferred)
 *   - LOCALES_WITH_TRANSLATIONS -> from all collected locales
 *   - FULLY_TRANSLATED_LOCALES  -> locales that have ALL namespace keys
 */
export function buildRuntimeConstantsContent(collected: CollectedData, defaultLocale: string): string {
  const source = schemaSourceLocale(collected, defaultLocale)
  const namespaceKeys = Object.keys((source && collected[source]) || {}).sort()
  const locales = localesWithTranslations(collected)

  const fullyTranslatedLocales = locales.filter((locale) => {
    const localeNamespaces = Object.keys(collected[locale] || {})
    return namespaceKeys.every((ns) => localeNamespaces.includes(ns))
  })

  return `${HEADER}
export const NAMESPACE_KEYS = [${namespaceKeys.map(quoteString).join(', ')}] as [string, ...string[]];

export const LOCALES_WITH_TRANSLATIONS = [${locales.map(quoteString).join(', ')}] as const;

export const FULLY_TRANSLATED_LOCALES = [${fullyTranslatedLocales.map(quoteString).join(', ')}] as const;
`
}

/**
 * `fallbacks.generated.ts`: one `FALLBACK_<NAMESPACE>` per default-locale namespace.
 * Null when the default locale has no translations (nothing to fall back to).
 */
export function buildFallbacksContent(collected: CollectedData, defaultLocale: string): string | null {
  const fallbackNamespaces = collected[defaultLocale]
  if (!fallbackNamespaces) return null

  const lines: string[] = [HEADER]
  lines.push(`export const FALLBACK_LOCALE = ${JSON.stringify(defaultLocale)} as const;\n`)

  for (const [ns, json] of Object.entries(fallbackNamespaces)) {
    const constName = `FALLBACK_${ns.toUpperCase()}`
    lines.push(`export const ${constName} = ${JSON.stringify(json, null, 2)} as const;\n`)
  }

  return lines.join('\n')
}
